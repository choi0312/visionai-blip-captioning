"""Visualize saved captions, decoding metrics, real cross-attention, and Korean translations."""
from pathlib import Path
import os,json,textwrap,urllib.request
import numpy as np
from PIL import Image
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.font_manager import FontProperties
ROOT=Path(os.environ.get('VISIONAI_ROOT','/content/visionai_week12'));D=ROOT/'data';R=ROOT/'results';F=ROOT/'figures';F.mkdir(exist_ok=True)
manifest=json.loads((D/'manifest.json').read_text());images={r['image_id']:r for r in manifest['images']}
caps=json.loads((R/'captions.json').read_text());byid={r['image_id']:r for r in caps}
m=json.loads((R/'metrics.json').read_text());per=json.loads((R/'per_image_metrics.json').read_text())
plt.rcParams.update({'font.family':'DejaVu Sans','font.size':10,'axes.spines.top':False,'axes.spines.right':False,'savefig.dpi':190})
def img(i):return Image.open(D/images[i]['file_name']).convert('RGB')
def wrap(s,n=47):return '\n'.join(textwrap.wrap(s,n))
def save(fig,name):fig.savefig(F/name,bbox_inches='tight',pad_inches=.08);plt.close(fig)
# Lowest and highest metric-rank cases, selected after evaluation for explanation only.
order=sorted(per['beam3'],key=lambda r:(r['CIDEr'],r['image_id']))
example_ids=[order[k]['image_id'] for k in [0,99]]
fig,axs=plt.subplots(1,2,figsize=(10,3.5))
for ax,i in zip(axs.flat,example_ids):
 ax.imshow(img(i));ax.set_xticks([]);ax.set_yticks([]);ax.set_title(f'COCO {i} | CIDEr {next(r["CIDEr"] for r in per["beam3"] if r["image_id"]==i):.3f}',fontsize=9)
 text='G: '+byid[i]['greedy']['caption']+'\nB3: '+byid[i]['beam3']['caption']+'\nRef 1/5: '+images[i]['references'][0]
 ax.set_xlabel('\n'.join(wrap(line,58) for line in text.splitlines()),fontsize=9,ha='center')
fig.tight_layout(h_pad=1.0);save(fig,'caption_examples.png')
fig,axs=plt.subplots(1,3,figsize=(10,2.55))
for ax,key,title in zip(axs,['BLEU_4','CIDEr','mean_ptb_words'],['Corpus BLEU-4 (0-1)','CIDEr (library scale)','Mean PTB words']):
 vals=[m['conditions'][c][key] for c in ['greedy','beam3']];bars=ax.bar([0,1],vals,color=['#337da5','#d08232'])
 ax.set_xticks([0,1],['Greedy','Beam 3']);ax.set_title(title,fontsize=10);ax.set_ylim(0,max(vals)*1.23)
 for bar,v in zip(bars,vals):ax.text(bar.get_x()+bar.get_width()/2,v+max(vals)*.025,f'{v:.4f}' if key!='mean_ptb_words' else f'{v:.2f}',ha='center',fontsize=9)
fig.tight_layout();save(fig,'decoding_comparison.png')
# First two predeclared attention cases, first 2 distinct non-stopword whole WordPieces.
att=np.load(R/'cross_attention.npz');ameta=json.loads((R/'attention_records.json').read_text())
stop=set('a an the is are was were this that in on at of with and to by for it its there some one two'.split())
attention_examples=[]
for rec in ameta[:2]:
 selected=[];seen=set()
 for j,t in enumerate(rec['predicted_tokens']):
  if t.isalpha() and t not in stop and t not in seen:
   selected.append((j,t));seen.add(t)
  if len(selected)==2:break
 assert len(selected)==2
 attention_examples.append({'image_id':rec['image_id'],'rows':[j for j,t in selected],'tokens':[t for j,t in selected]})
all_maps=[att[str(e['image_id'])][j,1:].reshape(24,24) for e in attention_examples for j in e['rows']]
# Remove the CLS attention mass and renormalize the 576 patch weights only for display.
all_maps=[a/a.sum() for a in all_maps];vmax=float(max(a.max() for a in all_maps))
fig,axs=plt.subplots(2,3,figsize=(10,3.8));k=0
for row,e in enumerate(attention_examples):
 original=img(e['image_id']);axs[row,0].imshow(original);axs[row,0].set_title(f'COCO {e["image_id"]}',fontsize=9)
 for col,(j,t) in enumerate(zip(e['rows'],e['tokens']),start=1):
  axs[row,col].imshow(original);a=all_maps[k];k+=1
  axs[row,col].imshow(a,cmap='magma',vmin=0,vmax=vmax,alpha=.58,extent=(0,original.width,original.height,0),interpolation='bilinear')
  axs[row,col].set_title(f'Predict "{t}" | row {j}',fontsize=9)
 for ax in axs[row]:ax.set_xticks([]);ax.set_yticks([])
fig.tight_layout(h_pad=1.3,w_pad=.6);save(fig,'cross_attention.png')
# Korean is generated by the translation model; preserve its raw output verbatim.
font_dir=ROOT/'fonts';font_dir.mkdir(exist_ok=True)
local_font=Path('/Applications/Microsoft Word.app/Contents/Resources/DFonts/malgun.ttf')
font=local_font if local_font.exists() else font_dir/'NotoSansCJKkr-Regular.otf'
if not font.exists():font.write_bytes(urllib.request.urlopen('https://raw.githubusercontent.com/notofonts/noto-cjk/main/Sans/OTF/Korean/NotoSansCJKkr-Regular.otf',timeout=90).read())
ko_font=FontProperties(fname=font)
translation_ids=[caps[0]['image_id'],caps[1]['image_id']]
fig,axs=plt.subplots(2,2,figsize=(10,3.0),gridspec_kw={'width_ratios':[1,2.4]})
for row,i in enumerate(translation_ids):
 axs[row,0].imshow(img(i));axs[row,0].set_title(f'COCO {i}',fontsize=9);axs[row,0].set_xticks([]);axs[row,0].set_yticks([])
 ax=axs[row,1];ax.axis('off')
 ax.text(0,.93,'BLIP English (beam 3)',fontsize=10,weight='bold',va='top')
 ax.text(0,.76,wrap(byid[i]['beam3']['caption'],70),fontsize=10,va='top')
 ax.text(0,.43,'M2M100 English -> Korean (raw output)',fontsize=10,weight='bold',va='top')
 ax.text(0,.25,wrap(byid[i]['korean']['text'],45),fontproperties=ko_font,fontsize=10,va='top')
fig.tight_layout(h_pad=.9);save(fig,'korean_translation.png')
selection={'caption_examples':{'rule':'beam3 per-image CIDEr ranks 0 and 99 after sorting by score then ID; post-hoc explanatory extremes, not a representative random subsample','ids':example_ids},
 'attention_examples':attention_examples,'attention_display':{'source':'final decoder layer, 12-head mean, prefix row predicts next token; CLS removed and patch mass renormalized','shared_vmin':0,'shared_vmax':vmax,'causal_explanation':False},
 'translation_examples':{'rule':'first two predeclared sorted sample IDs; raw translation outputs','ids':translation_ids}}
(R/'selected_examples.json').write_text(json.dumps(selection,ensure_ascii=False,indent=2)+'\n')
print('FIGURES_DONE',json.dumps(selection),flush=True)
